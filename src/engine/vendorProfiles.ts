export function getEffectiveAd(
  vendor: VendorProfile,
  protocol: ProtocolType,
  overrides: Partial<Record<ProtocolType, number>>,
  ospfType?: 'intra' | 'inter' | 'ext1' | 'ext2'
): number {
  if (overrides[protocol] !== undefined) {
    return overrides[protocol]!;
  }
  if (
    vendor === 'pan-os' &&
    protocol === 'ospf' &&
    (ospfType === 'ext1' || ospfType === 'ext2')
  ) {
    return 110;
  }
  if (
    vendor === 'juniper-junos' &&
    protocol === 'ospf' &&
    (ospfType === 'ext1' || ospfType === 'ext2')
  ) {
    return 150;
  }
  return VENDOR_DEFAULT_AD[vendor][protocol] ?? 255;
}

